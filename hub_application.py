"""HUB loan-status demo: prediction, local SHAP and interest-rate-only CFE.

Requires artifacts generated by the revised notebook. Training is NOT performed here.
Trusted local .pkl files only. Execute on Google Colab or local Python.
"""
from __future__ import annotations

import argparse
from pathlib import Path
from time import perf_counter

import joblib
import numpy as np
import pandas as pd


class HUBApplication:
    def __init__(self, model_path='HUB_Credit_Risk_Model.pkl',
                 cfe_path='HUB_CFE_Reference.pkl', data_path='loan_test.csv'):
        self.model_package = joblib.load(model_path)
        self.cfe_package = joblib.load(cfe_path)
        self.pipeline = self.model_package['pipeline']
        self.threshold = float(self.model_package['threshold'])
        if 'cfe_target_probability' not in self.cfe_package:
            raise ValueError('File CFE .pkl thiếu cfe_target_probability; cần lưu lại Bước 10.2.')
        self.cfe_target_probability = float(self.cfe_package['cfe_target_probability'])
        if not (0 < self.cfe_target_probability < self.threshold):
            raise ValueError('Mục tiêu CFE phải > 0 và nhỏ hơn threshold phân loại.')
        self.input_columns = list(self.model_package['input_columns'])
        self.data_path = str(data_path)
        self.frame = pd.read_csv(data_path)
        if 'id' not in self.frame.columns:
            raise ValueError("CSV thiếu cột 'id'.")
        if self.frame['id'].isna().any() or self.frame['id'].duplicated().any():
            raise ValueError("Cột 'id' phải duy nhất và không thiếu.")
        if not np.isclose(float(self.cfe_package['threshold']), self.threshold):
            raise ValueError('Threshold không khớp giữa hai file .pkl.')
        if list(self.cfe_package['actionable_features']) != ['int_rate']:
            raise ValueError('Chương trình này chỉ hỗ trợ CFE với int_rate.')
        if self.cfe_package['direction'] != 'decrease_only':
            raise ValueError('Cấu hình CFE phải là decrease_only.')
        missing = [c for c in self.input_columns if c not in self.frame.columns]
        if missing:
            raise ValueError(f'CSV thiếu các đặc trưng: {missing}')
        self.features = self._prepare(self.frame)
        self.screened_cfe = None
        self.valid_cfe = None

    def _prepare(self, frame: pd.DataFrame) -> pd.DataFrame:
        """Reproduce v1_7 Cell 9 raw transformations, before saved Pipeline."""
        X = frame[self.input_columns].copy()
        if 'term' in X:
            X['term'] = pd.to_numeric(
                X['term'].astype('string').str.replace(' months', '', regex=False).str.strip(),
                errors='coerce'
            )
        for col in ['int_rate', 'revol_util']:
            if col in X:
                X[col] = pd.to_numeric(
                    X[col].astype('string').str.replace('%', '', regex=False).str.strip(),
                    errors='coerce'
                )
        # issue_d, last_pymnt_d, last_credit_pull_d were dropped before pipeline.
        if 'earliest_cr_line' in X:
            dates = pd.to_datetime(X['earliest_cr_line'], format='%b-%y', errors='coerce')
            X['earliest_cr_line'] = dates.dt.year * 12 + dates.dt.month
        return X[self.input_columns]

    def _position(self, loan_id):
        # IDs can be passed as strings or integers, but never match approximately.
        matches = np.flatnonzero(self.frame['id'].astype(str).to_numpy() == str(loan_id))
        if len(matches) != 1:
            raise ValueError(f'Không tìm thấy ID duy nhất: {loan_id}')
        return int(matches[0])

    def predict(self, loan_id):
        pos = self._position(loan_id)
        p = float(self.pipeline.predict_proba(self.features.iloc[[pos]])[0, 1])
        info = {
            'ID': self.frame.iloc[pos]['id'],
            'P(Charged Off)': p,
            'Threshold': self.threshold,
            'Predicted loan_status': int(p >= self.threshold),
            'int_rate (%)': self.features.iloc[pos]['int_rate'],
            'term (months)': self.features.iloc[pos]['term'],
        }
        if 'loan_status' in self.frame:
            info['Actual loan_status'] = self.frame.iloc[pos]['loan_status']
        return info

    def explain_shap(self, loan_id, max_display=15, show_plot=True):
        import shap
        import matplotlib.pyplot as plt
        from scipy.special import expit

        pos = self._position(loan_id)
        x_raw = self.features.iloc[[pos]]
        preprocess = self.pipeline.named_steps['preprocess']
        model = self.pipeline.named_steps['model']
        x = preprocess.transform(x_raw)
        if hasattr(x, 'toarray'):
            x = x.toarray()
        x = np.asarray(x, dtype=float)
        names = list(preprocess.get_feature_names_out())
        ex = shap.TreeExplainer(model, model_output='raw')(x)
        ex.feature_names = names
        values = np.asarray(ex.values).reshape(1, -1)[0]
        base = float(np.asarray(ex.base_values).ravel()[0])
        margin = base + float(values.sum())
        expected_margin = float(model.predict(x, output_margin=True)[0])
        actual_prob = float(self.pipeline.predict_proba(x_raw)[0, 1])
        if not np.isclose(margin, expected_margin, atol=1e-4):
            raise AssertionError('SHAP không khớp raw margin.')
        if not np.isclose(float(expit(margin)), actual_prob, atol=1e-5):
            raise AssertionError('SHAP không khớp xác suất mô hình.')
        table = pd.DataFrame({'Feature': names, 'Feature Value': x[0], 'SHAP (log-odds)': values})
        table['Abs SHAP'] = table['SHAP (log-odds)'].abs()
        table = table.sort_values('Abs SHAP', ascending=False).reset_index(drop=True)
        if show_plot:
            shap.plots.waterfall(ex[0], max_display=max_display, show=False)
            plt.title(f'Local SHAP - Loan ID {loan_id}')
            plt.tight_layout()
            plt.show()
        return {'ID': loan_id, 'Base (log-odds)': base,
                'Sum SHAP': float(values.sum()), 'Margin': margin,
                'Probability': actual_prob, 'SHAP table': table}

    def cfe(self, loan_id):
        """Smallest grid reduction reaching the saved CFE target; otherwise show largest tried."""
        pos = self._position(loan_id)
        original = self.features.iloc[[pos]].copy()
        rate = float(original['int_rate'].iloc[0])
        p0 = float(self.pipeline.predict_proba(original)[0, 1])
        pred0 = int(p0 >= self.threshold)
        result = {
            'ID': loan_id, 'Original Rate (%)': rate,
            'Original Probability': p0, 'Original Prediction': pred0,
            'Classification Threshold': self.threshold,
            'CFE Target Probability': self.cfe_target_probability,
            'New Rate (%)': np.nan, 'Reduction (pp)': np.nan,
            'New Probability': np.nan, 'New Prediction': np.nan,
            'Status': 'Not predicted class 1' if not pred0 else 'No valid CFE',
        }
        if not pred0:
            return result
        min_rate = float(self.cfe_package['rate_min'])
        max_drop = float(self.cfe_package['max_reduction'])
        grid = np.asarray(self.cfe_package['reduction_grid'], dtype=float)
        grid = np.sort(np.unique(grid[(grid > 0) & (grid <= max_drop + 1e-8)]))
        grid = grid[rate - grid >= min_rate - 1e-8]
        if len(grid) == 0:
            result['Status'] = 'No feasible reduction'
            return result
        candidates = pd.concat([original] * len(grid), ignore_index=True)
        candidates['int_rate'] = rate - grid
        # Exact equality of other features, including NaNs.
        for col in original.columns.drop('int_rate'):
            v = original.iloc[0][col]
            if pd.isna(v):
                assert candidates[col].isna().all(), f'Unexpected change: {col}'
            else:
                assert candidates[col].eq(v).all(), f'Unexpected change: {col}'
        probabilities = self.pipeline.predict_proba(candidates)[:, 1]
        indices = np.flatnonzero(probabilities <= self.cfe_target_probability)
        valid = len(indices) > 0
        i = int(indices[0]) if valid else len(grid) - 1
        p1 = float(probabilities[i])
        result.update({
            'New Rate (%)': float(candidates['int_rate'].iloc[i]),
            'Reduction (pp)': float(grid[i]),
            'New Probability': p1,
            'New Prediction': int(p1 >= self.threshold),
            'Status': 'Valid CFE' if valid else 'No valid CFE'
        })
        return result

    def screen_cfe(self, print_every=100):
        """Scan ALL predicted class-1 records in uploaded CSV; no Test labels required.

        Returns (all_screened, valid_only, summary). Does not retrain or
        change the trained pipeline/threshold. The CFE grid is in the .pkl.
        """
        started = perf_counter()
        probabilities = self.pipeline.predict_proba(self.features)[:, 1]
        predicted_positions = np.flatnonzero(probabilities >= self.threshold)
        if len(predicted_positions) == 0:
            raise ValueError('Không có hồ sơ được dự đoán lớp 1 trong file CSV.')

        results = []
        for k, pos in enumerate(predicted_positions, start=1):
            identifier = self.frame.iloc[pos]['id']
            result = self.cfe(identifier)
            # Check consistency with the batch predictions on this dataset.
            if not np.isclose(result['Original Probability'], probabilities[pos], atol=1e-7):
                raise AssertionError(f'Xác suất không khớp ở ID {identifier}.')
            if 'loan_status' in self.frame.columns:
                result['Actual Label'] = self.frame.iloc[pos]['loan_status']
            results.append(result)
            if print_every and k % print_every == 0:
                print(f'Đã khảo sát {k}/{len(predicted_positions)} hồ sơ')

        all_records = pd.DataFrame(results)
        valid_mask = (
            all_records['Status'].eq('Valid CFE')
            & all_records['New Probability'].le(self.cfe_target_probability + 1e-8)
            & all_records['New Prediction'].eq(0)
            & all_records['Reduction (pp)'].gt(0)
            & all_records['Reduction (pp)'].le(float(self.cfe_package['max_reduction']) + 1e-8)
            & all_records['New Rate (%)'].ge(float(self.cfe_package['rate_min']) - 1e-8)
        )
        if not valid_mask.equals(all_records['Status'].eq('Valid CFE')):
            raise AssertionError('Có CFE được gắn nhãn hợp lệ nhưng không đạt ràng buộc.')
        valid = all_records.loc[valid_mask].copy().reset_index(drop=True)
        total = len(all_records)
        count = len(valid)
        reductions = valid['Reduction (pp)']
        summary = pd.DataFrame([
            ('Input CSV', str(self.data_path)),
            ('Total CSV records', len(self.frame)),
            ('Predicted class 1', total),
            ('Valid CFE', count),
            ('No valid CFE', total - count),
            ('Validity rate (%)', 100 * count / total),
            ('Model threshold', self.threshold),
            ('CFE target probability', self.cfe_target_probability),
            ('Minimum interest rate (%)', float(self.cfe_package['rate_min'])),
            ('Grid step (pp)', float(self.cfe_package['rate_step'])),
            ('Maximum reduction (pp)', float(self.cfe_package['max_reduction'])),
            ('Median valid reduction (pp)', reductions.median() if count else np.nan),
            ('Mean valid reduction (pp)', reductions.mean() if count else np.nan),
            ('P25 valid reduction (pp)', reductions.quantile(.25) if count else np.nan),
            ('P75 valid reduction (pp)', reductions.quantile(.75) if count else np.nan),
            ('P90 valid reduction (pp)', reductions.quantile(.90) if count else np.nan),
            ('P95 valid reduction (pp)', reductions.quantile(.95) if count else np.nan),
        ], columns=['Metric', 'Value'])
        self.screened_cfe = all_records
        self.valid_cfe = valid
        self.cfe_summary = summary
        print(f'Đã khảo sát {total} hồ sơ dự đoán lớp 1; đạt mục tiêu CFE <= {self.cfe_target_probability:.2f}: {count} ({count/total:.2%}); '
              f'không tìm được CFE: {total-count}; thời gian: {perf_counter()-started:.1f}s')
        if 'loan_status' not in self.frame.columns:
            print('CSV không có loan_status: không thể xác định TP/FP hoặc nhãn thực tế.')
        return all_records, valid, summary

    def export_cfe_excel(self, path='HUB_CFE_Valid_21Features_Target045_App.xlsx'):
        """Export the screening already performed; requires screen_cfe first."""
        if self.valid_cfe is None or self.screened_cfe is None:
            raise RuntimeError('Hãy gọi app.screen_cfe() trước khi xuất Excel.')
        # Excel file created on user's Colab using pandas + xlsxwriter.
        with pd.ExcelWriter(path, engine='xlsxwriter') as writer:
            valid_export = self.valid_cfe.sort_values(['Reduction (pp)', 'ID']).reset_index(drop=True)
            valid_export.to_excel(writer, sheet_name='CFE_Valid', index=False)
            self.cfe_summary.to_excel(writer, sheet_name='CFE_Summary', index=False)
            self.screened_cfe.to_excel(writer, sheet_name='All_Screened', index=False)
            workbook = writer.book
            header = workbook.add_format({'bold': True, 'bg_color': '#19324D', 'font_color': '#FFFFFF', 'border': 0})
            number_fmt = workbook.add_format({'num_format': '0.0000'})
            for sheet_name, data in [('CFE_Valid', valid_export), ('CFE_Summary', self.cfe_summary),
                                     ('All_Screened', self.screened_cfe)]:
                worksheet = writer.sheets[sheet_name]
                worksheet.freeze_panes(1, 0)
                worksheet.autofilter(0, 0, len(data), len(data.columns) - 1)
                for idx, col in enumerate(data.columns):
                    width = min(30, max(14, len(str(col)) + 2))
                    worksheet.set_column(idx, idx, width)
                    worksheet.write(0, idx, col, header)
                if sheet_name != 'CFE_Summary':
                    for idx, col in enumerate(data.columns):
                        if pd.api.types.is_float_dtype(data[col]):
                            worksheet.set_column(idx, idx, 23, number_fmt)
        print(f'Đã xuất {path}: {len(self.valid_cfe)} CFE hợp lệ.')
        return str(path)

    def analyze_id(self, loan_id, show_shap=True):
        """Display original prediction, matching CFE and SHAP for one uploaded CSV ID."""
        self.analyze(loan_id, show_shap=show_shap)
        if self.screened_cfe is not None:
            row = self.screened_cfe.loc[self.screened_cfe['ID'].astype(str).eq(str(loan_id))]
            if len(row):
                print('\nKẾT QUẢ CFE TRONG DANH SÁCH ĐÃ KHẢO SÁT')
                print(row.to_string(index=False))

    def analyze(self, loan_id, show_shap=True):
        print('\nDỰ ĐOÁN')
        print(pd.Series(self.predict(loan_id)).to_string())
        print(f'\nCFE - CHỈ GIẢM LÃI SUẤT (MỤC TIÊU <= {self.cfe_target_probability:.2f})')
        print(pd.Series(self.cfe(loan_id)).to_string())
        if show_shap:
            print('\nLOCAL SHAP (RAW MARGIN / LOG-ODDS)')
            r = self.explain_shap(loan_id)
            print(r['SHAP table'].head(15).round(4).to_string(index=False))



def run_cfe_screening(model_path='HUB_Credit_Risk_Model.pkl',
                      cfe_path='HUB_CFE_Reference.pkl',
                      data_path='loan_test.csv',
                      excel_path='HUB_CFE_Valid_21Features_Target045_App.xlsx',
                      print_every=100,
                      export_excel=True):
    """One-call workflow: load saved model + CFE settings, scan CSV, export results.

    Upload the four files (including hub_application.py) to Colab first, then:
        from hub_application import run_cfe_screening
        app, df_all, df_valid, df_summary = run_cfe_screening()

    No interactive ID, SHAP, refitting, threshold tuning, or calibration.
    """
    needed = [model_path, cfe_path, data_path]
    missing = [str(p) for p in needed if not Path(p).is_file()]
    if missing:
        raise FileNotFoundError(
            'Chưa có các file đầu vào trong thư mục hiện hành: ' + ', '.join(missing)
        )

    app = HUBApplication(model_path=model_path, cfe_path=cfe_path,
                         data_path=data_path)
    print('KHẢO SÁT CFE - LOAN_TEST.CSV')
    print(f'Tổng hồ sơ: {len(app.frame)}')
    print(f'Số biến đầu vào: {len(app.input_columns)}')
    print(f'Threshold từ mô hình đã lưu: {app.threshold:.4f}')
    print(f'Mục tiêu CFE từ cấu hình đã lưu: <= {app.cfe_target_probability:.4f}')
    print('Biến thay đổi: int_rate (chỉ giảm)')
    print('Không sử dụng Calibration hoặc huấn luyện lại mô hình.\n')

    df_all, df_valid, df_summary = app.screen_cfe(print_every=print_every)
    print('\nBẢNG TỔNG HỢP')
    print(df_summary.to_string(index=False))
    print('\n10 CFE HỢP LỆ ĐẦU TIÊN')
    print(df_valid.head(10).round(4).to_string(index=False))

    if export_excel:
        try:
            result_path = app.export_cfe_excel(excel_path)
        except ModuleNotFoundError as exc:
            if exc.name == 'xlsxwriter':
                raise ModuleNotFoundError(
                    'Thiếu thư viện XlsxWriter để xuất Excel. '
                    'Trong Colab chạy: %pip install -q XlsxWriter; '
                    'sau đó chạy app.export_cfe_excel('
                    f'{excel_path!r}) (không cần khảo sát lại).'
                ) from exc
            raise
        print(f'File Excel đã tạo: {result_path}')
    return app, df_all, df_valid, df_summary


def run_colab(model_path='HUB_Credit_Risk_Model.pkl',
              cfe_path='HUB_CFE_Reference.pkl', data_path='loan_test.csv'):
    """Upload three artifacts as needed, ask for ID, run prediction, SHAP and CFE."""
    needed = [model_path, cfe_path, data_path]
    if any(not Path(p).exists() for p in needed):
        from google.colab import files
        print('Hãy tải lên HUB_Credit_Risk_Model.pkl, HUB_CFE_Reference.pkl và loan_test.csv')
        files.upload()
    missing = [p for p in needed if not Path(p).exists()]
    if missing:
        raise FileNotFoundError('Chưa có file: ' + ', '.join(missing))
    app = HUBApplication(model_path, cfe_path, data_path)
    print(f'Đã nạp {len(app.frame)} hồ sơ. Threshold = {app.threshold:.2f}')
    loan_id = input('Nhập ID hồ sơ cần tra cứu: ').strip()
    if not loan_id:
        raise ValueError('Bạn chưa nhập ID.')
    app.analyze(loan_id)
    return app


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='HUB Loan Default Demo')
    parser.add_argument('--model', default='HUB_Credit_Risk_Model.pkl')
    parser.add_argument('--cfe', default='HUB_CFE_Reference.pkl')
    parser.add_argument('--data', default='loan_test.csv')
    parser.add_argument('--id', help='Loan ID for prediction, SHAP and CFE')
    parser.add_argument('--screen', action='store_true',
                        help='Scan all predicted class-1 records and export Excel')
    parser.add_argument('--excel', default='HUB_CFE_Valid_21Features_Target045_App.xlsx',
                        help='Excel output path for --screen')
    args = parser.parse_args()
    if args.screen:
        run_cfe_screening(model_path=args.model, cfe_path=args.cfe,
                          data_path=args.data, excel_path=args.excel)
    elif args.id:
        app = HUBApplication(args.model, args.cfe, args.data)
        app.analyze(args.id)
    else:
        parser.error('Cần cung cấp --screen hoặc --id.')
